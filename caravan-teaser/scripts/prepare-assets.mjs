// Prepares everything the Remotion compositions read at render time:
//  1. extracts the accent colour(s) from the logo        -> src/generated/brand.ts
//  2. makes a tightly-cropped copy of the logo (pixels    -> public/generated/logo-trimmed.png
//     untouched, only the empty transparent margin is cut)
//  3. scans /public/footage and /public/audio             -> src/generated/assets.ts
//  4. generates the PLACEHOLDER beat synced to config     -> public/generated/placeholder-beat.wav
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {PNG} from 'pngjs';
import {brand, hits, audio, DURATION_IN_FRAMES, FPS, FRAMES_PER_BEAT, scenes} from '../src/config.ts';
import {renderBeat} from './beat.mjs';

const root = path.resolve(import.meta.dirname, '..');
const pub = path.join(root, 'public');
const genSrc = path.join(root, 'src', 'generated');
const genPub = path.join(pub, 'generated');
fs.mkdirSync(genSrc, {recursive: true});
fs.mkdirSync(genPub, {recursive: true});

// ---------------------------------------------------------------- 1+2 logo
const logoPath = path.join(pub, brand.logoFile);
const png = PNG.sync.read(fs.readFileSync(logoPath));
const {width: W, height: H, data} = png;

let transparentCorners = 0;
for (const [x, y] of [[0, 0], [W - 1, 0], [0, H - 1], [W - 1, H - 1]]) {
  if (data[(y * W + x) * 4 + 3] < 10) transparentCorners++;
}
const hasTransparentBg = transparentCorners === 4;

const rgbToHsv = (r, g, b) => {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), d = max - min;
  let h = 0;
  if (d) {
    if (max === r) h = ((g - b) / d) % 6;
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h *= 60; if (h < 0) h += 360;
  }
  return [h, max ? d / max : 0, max];
};

const buckets = new Map(); // 10° hue buckets of saturated, opaque pixels
let minX = W, minY = H, maxX = 0, maxY = 0;
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    const i = (y * W + x) * 4;
    const [r, g, b, a] = [data[i], data[i + 1], data[i + 2], data[i + 3]];
    const visible = hasTransparentBg ? a > 8 : r + g + b < 735;
    if (visible) { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); }
    if (a < 200) continue;
    const [h, s, v] = rgbToHsv(r, g, b);
    if (s < 0.55 || v < 0.35) continue;
    const k = Math.floor(h / 10);
    const e = buckets.get(k) ?? {n: 0, r: 0, g: 0, b: 0};
    e.n++; e.r += r; e.g += g; e.b += b;
    buckets.set(k, e);
  }
}
const sorted = [...buckets.entries()].sort((a, b) => b[1].n - a[1].n);
const hex = (e) => '#' + [e.r / e.n, e.g / e.n, e.b / e.n].map((c) => Math.round(c).toString(16).padStart(2, '0')).join('').toUpperCase();
const accent = sorted.length ? hex(sorted[0][1]) : '#00AEEF';
const deepEntry = sorted.find(([k]) => Math.abs(k - (sorted[0]?.[0] ?? 0)) >= 2);
const accentDeep = deepEntry ? hex(deepEntry[1]) : accent;

// Crop the empty margin (no pixel of the artwork is changed).
const pad = Math.round(Math.max(W, H) * 0.01);
minX = Math.max(0, minX - pad); minY = Math.max(0, minY - pad);
maxX = Math.min(W - 1, maxX + pad); maxY = Math.min(H - 1, maxY + pad);
const cw = maxX - minX + 1, ch = maxY - minY + 1;
const out = new PNG({width: cw, height: ch});
PNG.bitblt(png, out, minX, minY, cw, ch, 0, 0);
fs.writeFileSync(path.join(genPub, 'logo-trimmed.png'), PNG.sync.write(out));

fs.writeFileSync(
  path.join(genSrc, 'brand.ts'),
  `// AUTO-GENERATED by scripts/prepare-assets.mjs — do not edit (override in src/config.ts)
export const extracted = {
  accent: '${accent}',
  accentDeep: '${accentDeep}',
  logoHasTransparentBackground: ${hasTransparentBg},
  logoTrimmed: {file: 'generated/logo-trimmed.png', width: ${cw}, height: ${ch}},
};
`,
);
console.log(`logo: ${W}x${H}, transparent background: ${hasTransparentBg}, trimmed to ${cw}x${ch}`);
console.log(`accent: ${accent}  secondary: ${accentDeep}`);
if (!hasTransparentBg) console.warn('WARNING: logo background is NOT transparent — it is shown on a white plate.');

// ---------------------------------------------------------------- 3 scan assets
const list = (dir, exts) =>
  fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => exts.includes(path.extname(f).toLowerCase())).sort() : [];
const videos = list(path.join(pub, 'footage'), ['.mp4', '.mov', '.webm', '.m4v']).map((f) => `footage/${f}`);
const audioFiles = list(path.join(pub, 'audio'), ['.mp3', '.wav', '.m4a', '.aac', '.ogg']);
const userMusic = audioFiles.find((f) => !f.startsWith('voiceover'));
const probe = (p) => {
  try {
    return parseFloat(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', p]).toString());
  } catch { return null; }
};
const recorded = {};
for (const lang of ['en', 'fa']) {
  const f = audioFiles.find((x) => x.startsWith(`voiceover-${lang}.`));
  const d = f ? probe(path.join(pub, 'audio', f)) : null;
  recorded[lang] = d ? {file: `audio/${f}`, durationInSeconds: d} : null;
}

fs.writeFileSync(
  path.join(genSrc, 'assets.ts'),
  `// AUTO-GENERATED by scripts/prepare-assets.mjs — re-run "npm run prepare-assets" after adding files
export const detected = {
  footage: ${JSON.stringify(videos)} as string[],
  userMusic: ${JSON.stringify(userMusic ? `audio/${userMusic}` : null)} as string | null,
  placeholderMusic: 'generated/placeholder-beat.wav',
  /** Recorded voiceovers (/public/audio/voiceover-en.* / voiceover-fa.*) — these override the AI narration. */
  recordedVoiceover: ${JSON.stringify(recorded)} as Record<'en' | 'fa', null | {file: string; durationInSeconds: number}>,
};
`,
);
console.log(`footage clips: ${videos.length}, user music: ${userMusic ?? 'none (placeholder beat)'}, recorded voiceover: en=${recorded.en ? 'yes' : 'no'} fa=${recorded.fa ? 'yes' : 'no'}`);

// ---------------------------------------------------------------- 4 placeholder beat
const wav = renderBeat({hits, scenes, fps: FPS, framesPerBeat: FRAMES_PER_BEAT, durationInFrames: DURATION_IN_FRAMES, fadeOutFrames: audio.fadeOutFrames});
fs.writeFileSync(path.join(genPub, 'placeholder-beat.wav'), wav);
console.log('placeholder beat written (PLACEHOLDER — replace with a licensed track)');
